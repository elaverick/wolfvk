#ifndef WOLF_AUDIO_ADLIB_SYNTH_H
#define WOLF_AUDIO_ADLIB_SYNTH_H

#include "adlib_archive.h"

#include <stdbool.h>
#include <stdint.h>

#define WOLF_AUDIO_ADLIB_SAMPLE_RATE 44100u
#define WOLF_AUDIO_ADLIB_TICK_RATE 140u

typedef struct WolfAudioPcm16 {
    int16_t *samples;
    uint32_t frame_count;
    uint32_t sample_rate;
} WolfAudioPcm16;

/*
 * Render one original AdLib sound effect using its 16-byte instrument and
 * frequency-byte stream. The original engine advances that stream at 140 Hz.
 */
bool wolf_audio_adlib_render(
    const WolfAudioAdlibSound *sound,
    WolfAudioPcm16 *rendered);

/* Release PCM generated by wolf_audio_adlib_render. */
void wolf_audio_pcm16_destroy(WolfAudioPcm16 *rendered);

#endif
